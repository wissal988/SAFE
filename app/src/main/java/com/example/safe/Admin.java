package com.example.safe;

public class Admin {

    public String uid;
    public String nom;
    public String prenom;
    public String telephone;
    public String email;

    public Admin() {}

    public Admin(String uid, String nom, String prenom, String telephone, String email) {
        this.uid = uid;
        this.nom = nom;
        this.prenom = prenom;
        this.telephone = telephone;
        this.email = email;
    }
}
